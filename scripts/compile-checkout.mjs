// Builds src/runtime/components/checkout.generated.js from @openreceive/vue's
// compiled Checkout (dist/Checkout.js, shipped as JS since 0.4.33): comments
// stripped, the relative `./index.js` import pointed at the package.
//
// Until 0.4.35 this script also patched the render function to bind the custom
// element's inputs as attributes (`prefix` is a read-only DOM property,
// Element.prototype.prefix, so binding it as a property dropped custom
// prefixes). Upstream does that itself since 0.4.35 (OpenReceive#132), so the
// file is now copied as is. The check below fails if that binding disappears.
//
// Run after bumping @openreceive/vue:  pnpm compile:checkout
// CI fails if the generated file is stale.
import { readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const out = `${root}src/runtime/components/checkout.generated.js`

const pkgDir = realpathSync(`${root}node_modules/@openreceive/vue`)
const version = JSON.parse(readFileSync(`${pkgDir}/package.json`, 'utf8')).version
let js = readFileSync(`${pkgDir}/dist/Checkout.js`, 'utf8')

// Strip comments (upstream prose, not needed at runtime) but keep the code as is.
js = js
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s*\/\/.*$/gm, '')
  .replace(/\n{3,}/g, '\n\n')

// The compiled file imports its own package entry relatively.
js = js.replace(/from\s+["']\.\/index\.js["']/g, 'from "@openreceive/vue"')
if (/from\s+["']\.\.?\//.test(js)) throw new Error('Unexpected relative import left in Checkout.js')

// Guard: both elements must still get their inputs as attributes (`^name`).
const bound = js.match(/asAttributes\(shell\.value\.(checkout|themeToggle)\.attributes\)/g) ?? []
if (bound.length !== 2) {
  throw new Error(`Expected Checkout.js to bind 2 elements' inputs as attributes, found ${bound.length}: check the upstream render function (OpenReceive#132)`)
}

writeFileSync(out, [
  `// GENERATED by scripts/compile-checkout.mjs from @openreceive/vue@${version} dist/Checkout.js. Do not edit.`,
  '// @ts-nocheck',
  '/* eslint-disable */',
  js.trim(),
  '',
].join('\n'))

console.log(`copied @openreceive/vue@${version} Checkout.js → ${out.replace(root, '')}`)
